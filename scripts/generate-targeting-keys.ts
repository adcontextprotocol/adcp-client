#!/usr/bin/env tsx
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.join(__dirname, '..');
const version = readFileSync(path.join(root, 'ADCP_VERSION'), 'utf8').trim();
const entries = [
  ['TargetingOverlay', 'targeting.json'],
  ['TargetingOverlaySupport', 'targeting-overlay-support.json'],
] as const;
let output = '// Generated by scripts/generate-targeting-keys.ts. Do not edit.\n';
output += "import type { TargetingOverlay, TargetingOverlaySupport } from './core.generated';\n\n";
for (const [name, file] of entries) {
  const schema = JSON.parse(readFileSync(path.join(root, 'schemas/cache', version, 'core', file), 'utf8'));
  if (!schema.properties || Object.keys(schema.properties).length === 0) {
    throw new Error(`${file}: expected top-level targeting properties.`);
  }
  const keys = Object.keys(schema.properties);
  output += `/** All ${name} keys in AdCP ${version}, including extension fields. */\n`;
  output += `export const ${name}Keys = Object.freeze(${JSON.stringify(keys, null, 2)} as const satisfies readonly (keyof ${name})[]);\n\n`;
}
writeFileSync(path.join(root, 'src/lib/types/targeting-keys.generated.ts'), output);
